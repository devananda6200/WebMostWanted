import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),build=path.join(root,'build');
const read=async file=>JSON.parse(await fs.readFile(path.join(build,file),'utf8'));
const manifest=await read('startup.json'),reference=await read('startup-reference.json');
const create=(await import(pathToFileURL(path.join(build,manifest.module)))).default;
const wasmBytes=await fs.readFile(path.join(build,'startup.wasm'));
assert.equal(createHash('sha256').update(wasmBytes).digest('hex'),manifest.artifact_sha256['startup.wasm'],'startup Wasm identity');
const m=await create({wasmBinary:wasmBytes});
const c=manifest.case;m._reset();
if(m._configure_platform)m._configure_platform(manifest.image.address);else m._win32_reset?.(manifest.image.address);
for(const region of c.regions)assert.equal(m._map_region(region.address,region.size,region.permissions),1);
const memory=m.HEAPU8.subarray(m._memory_base(),m._memory_base()+m._memory_size());
const imageBytes=await fs.readFile(path.join(build,manifest.image.url));
assert.equal(createHash('sha256').update(imageBytes).digest('hex'),manifest.image.sha256,'startup image identity');
memory.set(imageBytes,manifest.image.address);
for(const w of c.writes)memory.set(w.bytes,w.address);
c.registers.forEach((v,i)=>m._set_reg(i,v));m._set_flags(c.eflags);m._set_eip(c.entry);m._set_fs_base(c.fsBase);
assert.equal(m._run(c.maxSteps,reference.stop),1,m.UTF8ToString(m._fault_text()));
for(let i=0;i<8;i++)assert.equal(m._get_reg(i)>>>0,reference.expected.registers[i],`register${i}`);
assert.equal(m._get_flags()&reference.expected.flagsMask,reference.expected.eflags&reference.expected.flagsMask);
for(const w of reference.expected.memory)assert.deepEqual([...memory.subarray(w.address,w.address+w.bytes.length)],w.bytes,`memory0x${w.address.toString(16)}`);
assert.deepEqual(Array.from({length:m._get_trace_count()},(_,i)=>m._get_trace(i)>>>0),reference.trace);
const report={status:'passed',instructions:m._get_steps(),scope:reference.scope,input_sha256:reference.input_sha256,stop:reference.stop};
await fs.writeFile(path.join(root,'artifacts/startup-prefix-test.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
